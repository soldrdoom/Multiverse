/**
 * sample-logo-points.mjs
 *
 * Samples 10,000 colored pixels from multiverse-official-logo.png via sharp.
 * Outputs src/services/visualizer/logoPoints.ts with Float32Arrays for WebGL.
 *
 * Color buckets (2,000 each):
 *   purple : hue 260–320
 *   green  : hue  90–160
 *   blue   : hue 195–250
 *   cyan   : hue 160–195
 *   gold   : hue  25– 55  (solar/orange centre)
 *
 * Coordinates are normalized to NDC-ish range [-1, 1] (Y flipped for WebGL).
 * Z is 0 for all points (2-D formation, shader can add depth).
 */

import sharp from 'sharp';
import {fileURLToPath} from 'url';
import path from 'path';
import fs from 'fs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const IMG_PATH = path.resolve(
  __dirname,
  '../fluxer_app/assets/images/multiverse-official-logo.png',
);
const OUT_PATH = path.resolve(
  __dirname,
  '../fluxer_app/src/services/visualizer/logoPoints.ts',
);

const POINTS_PER_BUCKET = 2000;
const ALPHA_THRESHOLD = 40; // skip near-transparent px

// ── HSL conversion ──────────────────────────────────────────────
function rgbToHsl(r, g, b) {
  r /= 255; g /= 255; b /= 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b);
  const l = (max + min) / 2;
  if (max === min) return [0, 0, l];
  const d = max - min;
  const s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  let h;
  switch (max) {
    case r: h = (g - b) / d + (g < b ? 6 : 0); break;
    case g: h = (b - r) / d + 2; break;
    default: h = (r - g) / d + 4; break;
  }
  return [h * 60, s, l];
}

// ── Bucket classifier ────────────────────────────────────────────
function classify(r, g, b) {
  const [h, s, l] = rgbToHsl(r, g, b);
  if (s < 0.18 || l < 0.12 || l > 0.92) return null; // grey / white / black
  if (h >= 260 && h < 320) return 'purple';
  if (h >= 90  && h < 160) return 'green';
  if (h >= 195 && h < 260) return 'blue';
  if (h >= 160 && h < 195) return 'cyan';
  if (h >= 25  && h < 60 ) return 'gold';
  return null;
}

// ── Main ─────────────────────────────────────────────────────────
const {data, info} = await sharp(IMG_PATH)
  .ensureAlpha()
  .raw()
  .toBuffer({resolveWithObject: true});

const {width, height} = info;
console.log(`Image: ${width}x${height}`);

const buckets = {purple: [], green: [], blue: [], cyan: [], gold: []};

for (let y = 0; y < height; y++) {
  for (let x = 0; x < width; x++) {
    const i = (y * width + x) * 4;
    const r = data[i], g = data[i+1], b = data[i+2], a = data[i+3];
    if (a < ALPHA_THRESHOLD) continue;
    const label = classify(r, g, b);
    if (!label) continue;
    buckets[label].push({x, y, r, g, b});
  }
}

for (const [k, v] of Object.entries(buckets)) {
  console.log(`  ${k}: ${v.length} candidate pixels`);
}

// ── Uniform sampling ─────────────────────────────────────────────
function sampleUniform(arr, n) {
  if (arr.length <= n) {
    // pad by cycling
    const out = [...arr];
    let i = 0;
    while (out.length < n) { out.push(arr[i++ % arr.length]); }
    return out;
  }
  const step = arr.length / n;
  return Array.from({length: n}, (_, i) => arr[Math.round(i * step)]);
}

// ── Assemble output arrays ────────────────────────────────────────
// Layout: interleaved [x, y, z, r, g, b] per point, total 10000 points
// x,y: NDC −1..1 (y flipped), z = 0

const COLOR_RGBA = {
  purple: [0.55, 0.20, 0.85],
  green:  [0.15, 0.75, 0.30],
  blue:   [0.15, 0.50, 0.90],
  cyan:   [0.20, 0.85, 0.80],
  gold:   [1.00, 0.75, 0.10],
};

const positions = []; // x y z  * 10000
const colors    = []; // r g b  * 10000

for (const label of ['purple', 'green', 'blue', 'cyan', 'gold']) {
  const sampled = sampleUniform(buckets[label], POINTS_PER_BUCKET);
  const [cr, cg, cb] = COLOR_RGBA[label];
  for (const {x, y} of sampled) {
    const nx =  (x / width)  * 2 - 1;
    const ny = -((y / height) * 2 - 1); // flip Y for WebGL
    positions.push(nx, ny, 0);
    colors.push(cr, cg, cb);
  }
}

// ── Stringify as typed-array literals ────────────────────────────
function toF32Literal(arr) {
  return `new Float32Array([\n  ${arr.join(', ')}\n])`;
}

const ts = `/*
 * AUTO-GENERATED by scripts/sample-logo-points.mjs — DO NOT EDIT.
 * 10,000 logo-sampled particle positions & colors for WebGL instanced rendering.
 */

// targetPositions: Float32Array of [x, y, z] per point (10000 × 3 = 30000 floats)
export const targetPositions: Float32Array = ${toF32Literal(positions.map(v => +v.toFixed(5)))};

// targetColors: Float32Array of [r, g, b] per point (10000 × 3 = 30000 floats)
export const targetColors: Float32Array = ${toF32Literal(colors.map(v => +v.toFixed(4)))};

export const POINT_COUNT = ${positions.length / 3};
`;

fs.mkdirSync(path.dirname(OUT_PATH), {recursive: true});
fs.writeFileSync(OUT_PATH, ts, 'utf8');
console.log(`Written: ${OUT_PATH}  (${positions.length / 3} points)`);
