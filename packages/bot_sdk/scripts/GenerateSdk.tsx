/**
 * SDK code generator for @fluxer/bot_sdk.
 *
 * Reads fluxer_docs/api-reference/openapi.json (the committed, Phase 1.0-cleaned
 * spec — its `security` metadata is derived, not asserted) and emits:
 *
 *   - src/types/Api.generated.tsx      — TypeScript types for every schema in
 *     components.schemas (all types are generated, even for endpoints bots
 *     cannot call, because gateway payloads and shared shapes reference them).
 *   - src/rest/Endpoints.generated.tsx — operationId → {method, path, params}
 *     for the bot-callable set only: operations whose `security` includes
 *     `botToken`.
 *
 * Everything with judgement in it (transport, auth, rate limiting, gateway
 * lifecycle) is hand-written; the generator's job is types and paths, nothing
 * else. Do not hand-edit the .generated.tsx outputs — fix this script or the
 * spec instead.
 *
 * Usage:
 *   pnpm --filter @fluxer/bot_sdk generate          # rewrite generated files
 *   pnpm --filter @fluxer/bot_sdk generate --check  # drift check (wired into lint)
 */

